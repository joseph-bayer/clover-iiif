const Controls = ({
  _cloverViewerHasPlaceholder,
  config,
}: {
  _cloverViewerHasPlaceholder: boolean;
  config: Options;
}) => {
  const viewerState: ViewerContextStore = useViewerState();
  const { activeCanvas, plugins, vault } = viewerState;

  const canvas = vault.get({
    id: activeCanvas,
    type: "Canvas",
  }) as CanvasNormalized;

  function renderPlugins() {
    return plugins
      .filter((plugin) => plugin.imageViewer?.controls)
      .map((plugin, i) => {
        const PluginComponent = plugin.imageViewer?.controls
          ?.component as unknown as React.ElementType;
        return (
          <PluginComponent
            key={i}
            {...plugin?.imageViewer?.controls?.componentProps}
            canvas={canvas}
            useViewerDispatch={useViewerDispatch}
            useViewerState={useViewerState}
          ></PluginComponent>
        );
      });
  }

  return (
    <Wrapper
      data-testid="clover-iiif-image-openseadragon-controls"
      hasPlaceholder={_cloverViewerHasPlaceholder}
    >
      {config.showZoomControl && (
        <>
          <Button
            id={config.zoomInButton as string}
            label="zoom in"
            viewBoxX={32}
            viewBoxY={32}
          >
            <ZoomIn />
          </Button>
          <Button
            id={config.zoomOutButton as string}
            label="zoom out"
            viewBoxX={32}
            viewBoxY={32}
          >
            <ZoomOut />
          </Button>
        </>
      )}
      {config.showFullPageControl && (
        <Button id={config.fullPageButton as string} label="full page">
          <ZoomFullScreen />
        </Button>
      )}
      {config.showRotationControl && (
        <>
          <Button id={config.rotateRightButton as string} label="rotate right">
            <Rotate />
          </Button>
          <Button id={config.rotateLeftButton as string} label="rotate left">
            <Rotate />
          </Button>
        </>
      )}
      {/* TODO: Figure out how to programatically reset */}
      {config.showHomeControl && (
        <Button
          id={config.homeButton as string}
          label="reset"
          viewBoxX={26}
          viewBoxY={26}
        >
          <Reset />
        </Button>
      )}
      {renderPlugins()}
    </Wrapper>
  );
};

export default Controls;
